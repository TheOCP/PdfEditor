package com.theocp.pdfeditor

import java.util.Locale

/**
 * English / German. Keys are the English texts; the desktop dictionary is
 * shared (L10nTable.kt, generated) and phone-only texts are added below.
 */
object L10n {
    @Volatile var german = false
    private val table: Map<String, String> by lazy { desktopGerman + mobileGerman }
    fun t(en: String): String = if (german) table[en] ?: en else en
    fun f(en: String, vararg args: Any?): String =
        String.format(if (german) Locale.GERMANY else Locale.US, t(en), *args)
}

fun tr(en: String): String = L10n.t(en)
fun trf(en: String, vararg args: Any?): String = L10n.f(en, *args)

