# Generates L10nTable.kt from the desktop dictionary (src/i18n.cpp) so the
# phone and PC versions use exactly the same English / German wording.
# Usage: python gen_l10n.py <repo root>
import re
import sys

root = sys.argv[1]
src = open(root + '/src/i18n.cpp', encoding='utf-8').read()
body = src[src.index('kGerman[] = {'):src.index('};', src.index('kGerman[] = {'))]


def c_literal_bytes(lit):
    """Decode the inside of a C string literal (escapes incl. \\xNN) to bytes."""
    out = bytearray()
    i = 0
    while i < len(lit):
        c = lit[i]
        if c == '\\':
            n = lit[i + 1]
            if n == 'x':
                j = i + 2
                h = ''
                while j < len(lit) and len(h) < 2 and lit[j] in '0123456789abcdefABCDEF':
                    h += lit[j]
                    j += 1
                out.append(int(h, 16))
                i = j
                continue
            out += {'n': b'\n', 't': b'\t', '"': b'"', '\\': b'\\', "'": b"'"}.get(n, n.encode())
            i += 2
            continue
        out += c.encode('utf-8')
        i += 1
    return bytes(out)


# Each entry: { "lit" "lit"..., "lit" "lit"... },
entries = []
for m in re.finditer(r'\{\s*((?:"(?:[^"\\]|\\.)*"\s*)+),\s*((?:"(?:[^"\\]|\\.)*"\s*)+)\}', body):
    def join(group):
        return b''.join(c_literal_bytes(x) for x in re.findall(r'"((?:[^"\\]|\\.)*)"', group)).decode('utf-8')
    entries.append((join(m.group(1)), join(m.group(2))))


def kt(s):
    s = s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('$', '\\$')
    return '"' + s + '"'


lines = ['package com.theocp.pdfeditor', '',
         '// Generated by tools/gen_l10n.py from src/i18n.cpp - do not edit by hand.',
         'internal val desktopGerman: Map<String, String> = mapOf(']
for en, de in entries:
    lines.append('    ' + kt(en) + ' to ' + kt(de) + ',')
lines.append(')')
open(root + '/android/app/src/main/java/com/theocp/pdfeditor/L10nTable.kt', 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print(len(entries), 'entries')
