# Android adaptive icon with the same design as res/app.ico (tools/make_icon.ps1):
# red tile, white page with a folded corner, three grey text lines, dark pen.
# The PC tile (size s) maps onto the middle 64 dp of the 108 dp layer.
import math, sys

res = sys.argv[1]
S, O = 64.0, 22.0          # a little inside the 72 dp visible area: room on round masks
def X(u): return O + S * u

pw, ph = 0.52, 0.64
px, py = (1 - pw) / 2, (1 - ph) / 2
fold = pw * 0.32
def f(v): return f"{v:.2f}"

page = (f"M{f(X(px))},{f(X(py))} L{f(X(px + pw - fold))},{f(X(py))} L{f(X(px + pw))},{f(X(py + fold))} "
        f"L{f(X(px + pw))},{f(X(py + ph))} L{f(X(px))},{f(X(py + ph))} Z")
foldp = (f"M{f(X(px + pw - fold))},{f(X(py))} L{f(X(px + pw - fold))},{f(X(py + fold))} "
         f"L{f(X(px + pw))},{f(X(py + fold))} Z")
lines = ""
lh = 0.04
for i in range(3):
    ly = py + ph * (0.42 + 0.15 * i)
    x0, x1 = px + pw * 0.15, px + pw * 0.15 + pw * 0.7
    lines += f"M{f(X(x0))},{f(X(ly))} L{f(X(x1))},{f(X(ly))} L{f(X(x1))},{f(X(ly + lh))} L{f(X(x0))},{f(X(ly + lh))} Z "

# pen: round start cap, pointed (triangle) end like GDI+'s Triangle cap
sx, sy, ex, ey = X(0.80), X(0.50), X(0.52), X(0.84)
h = S * 0.09 / 2
dx, dy = ex - sx, ey - sy
L = math.hypot(dx, dy)
ux, uy = dx / L, dy / L
nx, ny = uy, -ux
A = (sx + nx * h, sy + ny * h)
B = (ex + nx * h, ey + ny * h)
C = (ex + ux * h, ey + uy * h)
D = (ex - nx * h, ey - ny * h)
E = (sx - nx * h, sy - ny * h)
pen = (f"M{f(A[0])},{f(A[1])} L{f(B[0])},{f(B[1])} L{f(C[0])},{f(C[1])} L{f(D[0])},{f(D[1])} L{f(E[0])},{f(E[1])} Z "
       f"M{f(sx - h)},{f(sy)} a{f(h)},{f(h)} 0 1,0 {f(2 * h)},0 a{f(h)},{f(h)} 0 1,0 {f(-2 * h)},0 Z")

xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Same design as the Windows icon (res/app.ico, tools/make_icon.ps1): a white
     page with a folded corner, text lines and a pen; the red tile is the
     background layer. Generated by android/tools/make_icon.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillColor="#FFFFFFFF" android:pathData="{page}" />
    <path android:fillColor="#FFF6B0AE" android:pathData="{foldp}" />
    <path android:fillColor="#FFBDBDBD" android:pathData="{lines.strip()}" />
    <path android:fillColor="#FF263238" android:pathData="{pen}" />
</vector>
'''
open(res + '/drawable/ic_launcher_foreground.xml', 'w', encoding='utf-8', newline='\n').write(xml)

adaptive = '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/icon_tile" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
'''
open(res + '/mipmap-anydpi-v26/ic_launcher.xml', 'w', encoding='utf-8', newline='\n').write(adaptive)

t = open(res + '/values/themes.xml', encoding='utf-8').read()
if 'icon_tile' not in t:
    t = t.replace('<color name="accent">#FF3B82F6</color>',
                  '<color name="accent">#FF3B82F6</color>\n    <color name="icon_tile">#FFE53935</color>', 1)
    open(res + '/values/themes.xml', 'w', encoding='utf-8').write(t)
print('ok')
